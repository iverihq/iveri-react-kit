/**
 * Writes `styles/tokens.css` from `@iveri/tokens`. With `--check` it writes nothing and fails when
 * the committed file differs from what it would write, which is how `pnpm build` and CI keep the
 * two from drifting.
 *
 * Only values are generated: every colour, radius, easing and duration, as Tailwind theme
 * variables. Everything that needs a sentence lives in the hand-written `styles/theme.css`, which
 * is what makes generating this half free — 0.8.0 declined to generate the stylesheet because it
 * was mostly reasoning, and the reasoning is no longer in the file being generated.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { color, duration, easing, productColor, radius } from '@iveri/tokens';
import { format, resolveConfig } from 'prettier';

const TARGET = resolve(import.meta.dirname, '../styles/tokens.css');
const NAMES_TARGET = resolve(import.meta.dirname, '../src/theme-check/theme-names.ts');

/** `lineStrong` → `line-strong`, the spelling both a custom property and a utility class want. */
const kebab = (name) => name.replace(/[A-Z]/gu, (letter) => `-${letter.toLowerCase()}`);

const block = (entries) => entries.map(([name, value]) => `    ${name}: ${value};`).join('\n');

const css = `/* Generated from @iveri/tokens by scripts/build-theme.mjs. Do not edit: run \`pnpm theme\`. */

/* \`static\`, so every token is a custom property in every app — hand-written CSS reads them by
 * name, and Tailwind would otherwise emit only the ones some utility happens to use. */
@theme static {
${block(Object.entries({ ...color, ...productColor }).map(([name, hex]) => [`--color-${kebab(name)}`, hex.toLowerCase()]))}

${block(Object.entries(radius).map(([name, pixels]) => [`--radius-${kebab(name)}`, `${pixels / 16}rem`]))}

${block(Object.entries(easing).map(([name, curve]) => [`--ease-${kebab(name)}`, curve]))}

${block(Object.entries(duration).map(([name, milliseconds]) => [`--duration-${kebab(name)}`, `${milliseconds}ms`]))}

    /* Tailwind's \`duration-*\` utilities read this namespace; \`--duration-*\` is the public name. */
${block(Object.keys(duration).map((name) => [`--transition-duration-${kebab(name)}`, `var(--duration-${kebab(name)})`]))}
}
`;

/**
 * The names `@iveri/react-kit/theme-check` accepts: every colour above, and the type sizes and
 * shadows the hand-written `styles/theme.css` declares (read from it, so a size added there is
 * known here without a second edit).
 */
const themeCss = readFileSync(resolve(import.meta.dirname, '../styles/theme.css'), 'utf8').replaceAll(
    /\/\*[\s\S]*?\*\//gu,
    '',
);
const declared = (namespace) => [
    ...new Set(
        [...themeCss.matchAll(new RegExp(`--${namespace}-([a-z0-9]+(?:-[a-z0-9]+)*):`, 'gu'))].map(([, name]) => name),
    ),
];
const list = (values) => `[\n${values.map((value) => `    '${value}',`).join('\n')}\n]`;
// Formatted the way `pnpm format` would, so the check and the formatter agree about the same file.
const names = await format(
    `// Generated by scripts/build-theme.mjs from @iveri/tokens and styles/theme.css. Do not edit: run \`pnpm theme\`.

/** Every colour the kit's theme defines: \`bg-<name>\`, \`text-<name>\`, \`border-<name>\` and the rest exist for these. */
export const THEME_COLOURS: readonly string[] = ${list(Object.keys({ ...color, ...productColor }).map(kebab))};

/** The type sizes the theme adds to Tailwind's own (\`text-<name>\`). */
export const THEME_TEXT_SIZES: readonly string[] = ${list(declared('text'))};

/** The shadows the theme defines (\`shadow-<name>\`). */
export const THEME_SHADOWS: readonly string[] = ${list(declared('shadow'))};
`,
    { ...(await resolveConfig(NAMES_TARGET)), filepath: NAMES_TARGET },
);

const outputs = [
    [TARGET, css],
    [NAMES_TARGET, names],
];

if (process.argv.includes('--check')) {
    const stale = outputs.filter(([path, content]) => readFileSync(path, 'utf8') !== content);
    if (stale.length > 0) {
        console.error(
            `${stale.map(([path]) => path).join(', ')} is not what @iveri/tokens generates — run \`pnpm theme\` and commit it.`,
        );
        process.exit(1);
    }
    console.log('@iveri/react-kit: styles/tokens.css and theme-names.ts match @iveri/tokens');
} else {
    for (const [path, content] of outputs) writeFileSync(path, content);
    console.log('@iveri/react-kit: wrote styles/tokens.css and theme-names.ts from @iveri/tokens');
}
